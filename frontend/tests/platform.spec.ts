test('signup generates the business code from the name and preserves edits', async ({ page }) => {
  await page.goto('/register');
  const name = page.getByLabel('Business name', { exact: true });
  const code = page.getByLabel('Business code', { exact: true });
  await expect(code).toHaveValue('');
  await name.fill('Golden Café & Kitchen');
  await expect(code).toHaveValue('golden-cafe-kitchen');
  await name.fill('Little Lemon');
  await expect(code).toHaveValue('little-lemon');
  await name.fill('A');
  await expect(code).toHaveValue('a-business');
  await name.fill('A'.repeat(59) + ' & Kitchen');
  await expect(code).toHaveValue('a'.repeat(59));
  await name.fill('');
  await expect(code).toHaveValue('');
  await name.fill('Golden Cafe');
  await code.fill('custom-cafe');
  await name.fill('Renamed Cafe');
  await expect(code).toHaveValue('custom-cafe');
});

