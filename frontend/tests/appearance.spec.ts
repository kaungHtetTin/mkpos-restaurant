test('appearance follows the system, persists, syncs tabs, and preserves form values',async({page},info)=>{
 await page.emulateMedia({colorScheme:'dark'});
 await page.goto('/');
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await expect(page.getByLabel('Appearance',{exact:true})).toHaveValue('system');
 const email=page.getByLabel('Email',{exact:true});await email.fill('saved@example.test');
 await page.evaluate(()=>{(window as any).__appearanceMount='retained';});
 const other=await page.context().newPage();await other.goto('/office');
 await page.getByLabel('Appearance',{exact:true}).selectOption('light');
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 await expect(other.locator('html')).toHaveAttribute('data-theme','light');
 await expect(email).toHaveValue('saved@example.test');
 expect(await page.evaluate(()=>(window as any).__appearanceMount)).toBe('retained');
 await page.getByLabel('Appearance',{exact:true}).selectOption('dark');
 await expect(other.getByLabel('Appearance',{exact:true})).toHaveValue('dark');
 await page.reload();await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.emulateMedia({colorScheme:'light'});await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.getByLabel('Appearance',{exact:true}).selectOption('system');
 await expect(page.locator('html')).toHaveAttribute('data-theme','light');
 await page.emulateMedia({colorScheme:'dark'});await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.screenshot({animations:'disabled',path:`test-results/${info.project.name}-dark-login.png`});
 await other.close();
});

