import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('manager configures rates and approves a discount with consistent checkout and receipt totals', async ({ page }, info) => {
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = 'charges-' + info.project.name + '-' + Date.now();
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Charges Owner', email: code + '@example.test', password: 'Charges123!', password_confirmation: 'Charges123!', business_name: 'Charges Test Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  const setup = await page.request.post('/api/v1/setup', { headers: { 'X-CSRF-TOKEN': account.csrf, 'Idempotency-Key': randomUUID() }, data: { name: 'Charges Test Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: true, tables: [], menu: [{ name: 'Rice', category: 'Main', price: 6500 }] } });
  expect(setup.ok()).toBeTruthy();
  await page.goto('/settings');
  await page.getByRole('button', { name: 'Tax & charges', exact: true }).click();
  await page.getByLabel('Tax name', { exact: true }).fill('Sales tax');
  await page.getByLabel('Tax rate (%)', { exact: true }).fill('5');
  await page.getByLabel('Service charge rate (%)', { exact: true }).fill('10');
  await page.getByLabel('Apply service charge to dine-in orders only', { exact: true }).uncheck();
  await page.getByLabel('Include service charge in the taxable amount', { exact: true }).check();
  await expect(page.locator('.charge-preview .bill-grand-total')).toContainText('11,550');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/' + info.project.name + '-charges-settings.png', fullPage: true });
  await page.getByRole('button', { name: 'Save charge settings', exact: true }).click();
  await expect(page.getByText('Charge settings saved. New orders will use these rates.', { exact: true })).toBeVisible();
  await page.goto('/takeaway');
  await page.getByRole('button', { name: 'New takeaway', exact: true }).first().click();
  await page.getByRole('button', { name: 'Start takeaway order', exact: true }).click();
  await page.getByRole('button', { name: 'Add Rice', exact: true }).click();
  if (info.project.name === 'phone') await page.getByRole('button', { name: /View order/ }).click();
  await page.getByRole('button', { name: 'Add discount', exact: true }).click();
  const discount = page.getByRole('dialog', { name: 'Order discount', exact: true });
  await discount.getByLabel('Discount (%)', { exact: true }).fill('10');
  await discount.getByLabel('Approval reason', { exact: true }).fill('Approved opening promotion');
  await expect(discount.locator('.bill-grand-total')).toContainText('6,757');
  await discount.getByRole('button', { name: 'Approve discount', exact: true }).click();
  await expect(discount).toHaveCount(0);
  await expect(page.locator('.cart-total')).toContainText('6,757');
  await page.getByRole('button', { name: 'Send 1 items to kitchen', exact: true }).click();
  await page.getByRole('button', { name: 'Collect payment', exact: true }).click();
  const checkout = page.getByRole('dialog');
  await expect(checkout.locator('.bill-breakdown')).toContainText('Sales tax (5%)');
  await expect(checkout.locator('.payment-total')).toContainText('6,757');
  await checkout.getByLabel('Cash received (MMK)', { exact: true }).fill('7000');
  await checkout.getByRole('button', { name: 'Confirm payment', exact: true }).click();
  const receipt = page.getByRole('dialog', { name: 'Payment complete', exact: true });
  await expect(receipt).toBeVisible();
  await expect(receipt.locator('.receipt-paper')).toContainText('Sales tax (5%)');
  await expect(receipt.locator('.receipt-paper-total')).toContainText('6,757');
  await expect(receipt.locator('.bill-discount')).toContainText('650');
  await page.screenshot({ path: 'test-results/' + info.project.name + '-discount-receipt.png', fullPage: true });
});
