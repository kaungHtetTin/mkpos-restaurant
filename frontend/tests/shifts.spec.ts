import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('cash drawer opens, reconciles payments and closes with a saved variance', async ({ page }, info) => {
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = 'shift-' + info.project.name + '-' + Date.now();
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Shift Owner', email: code + '@example.test', password: 'Shift123!', password_confirmation: 'Shift123!', business_name: 'Shift Test Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  const post = async (path: string, data: object) => {
    const response = await page.request.post('/api/v1/' + path, { headers: { 'X-CSRF-TOKEN': account.csrf, 'Idempotency-Key': randomUUID() }, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await post('setup', { name: 'Shift Test Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: true, tables: [], menu: [{ name: 'Rice', category: 'Main', price: 3500 }] });
  await page.goto('/tables');
  await expect(page.getByRole('heading', { name: 'Your floor, at a glance.' })).toBeVisible();
  if (info.project.name === 'phone') await page.getByRole('button', { name: 'More', exact: true }).click();
  await page.getByRole('link', { name: 'Cash shifts', exact: true }).filter({ visible: true }).click();
  await expect(page.getByRole('heading', { name: 'Cashier shifts.' })).toBeVisible();
  await page.getByRole('button', { name: 'Open shift', exact: true }).first().click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('Opening cash (MMK)', { exact: true }).fill('10000');
  await dialog.getByRole('button', { name: 'Open shift', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.shift-metric.highlight')).toContainText('10,000');
  await page.getByRole('button', { name: 'Record cash in / out', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox').selectOption('out');
  await dialog.getByLabel('Amount (MMK)', { exact: true }).fill('500');
  await dialog.getByLabel('Reason', { exact: true }).fill('Cash banked');
  await dialog.getByRole('button', { name: 'Record movement', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const state = await (await page.request.get('/api/v1/state')).json();
  let order = await post('orders', { type: 'takeaway' });
  order = await post(`orders/${order.id}/add-item`, { version: order.version, menu_item_id: state.menu[0].id, quantity: 1 });
  order = await post(`orders/${order.id}/submit`, { version: order.version });
  await post(`orders/${order.id}/pay`, { version: order.version, method: 'cash', tendered: 4000 });
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.locator('.shift-metric.highlight')).toContainText('13,000');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/' + info.project.name + '-shift-active.png', fullPage: true });
  await page.getByRole('button', { name: 'Close shift', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Counted cash (MMK)', { exact: true }).fill('12800');
  await expect(dialog.getByRole('status')).toContainText('Cash short');
  await dialog.getByLabel(/^Closing note/).fill('Reviewed: drawer short by 200');
  await dialog.getByRole('button', { name: 'Confirm closing count', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'No open shift', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /View shift/ }).click();
  await expect(page.getByRole('dialog')).toContainText('Reviewed: drawer short by 200');
  await page.screenshot({ path: 'test-results/' + info.project.name + '-shift-report.png', fullPage: true });
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.reload();
  await expect(page.locator('.shift-history tbody tr')).toHaveCount(1);
});
