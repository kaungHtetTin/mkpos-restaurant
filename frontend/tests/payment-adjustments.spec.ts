import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('manager corrections and refunds retain original receipts and reconcile reports and cash', async ({ page }, info) => {
  test.setTimeout(75000);
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = 'refund-' + info.project.name + '-' + Date.now();
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Refund Owner', email: code + '@example.test', password: 'Refund123!', password_confirmation: 'Refund123!', business_name: 'Refund Test Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  const post = async (path: string, data: object) => {
    const response = await page.request.post('/api/v1/' + path, { headers: { 'X-CSRF-TOKEN': account.csrf, 'Idempotency-Key': randomUUID() }, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await post('setup', { name: 'Refund Test Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: true, tables: [], menu: [{ name: 'Rice', category: 'Main', price: 6500 }] });
  await post('shifts/open', { opening_cash: 10000 });
  const state = await (await page.request.get('/api/v1/state')).json();
  let order = await post('orders', { type: 'takeaway' });
  order = await post(`orders/${order.id}/add-item`, { version: order.version, menu_item_id: state.menu[0].id, quantity: 1 });
  order = await post(`orders/${order.id}/submit`, { version: order.version });
  order = await post(`orders/${order.id}/pay`, { version: order.version, method: 'cash', tendered: 7000 });
  await page.goto(`/orders/${order.id}`);
  await page.getByRole('button', { name: 'Correct method', exact: true }).click();
  let dialog = page.getByRole('dialog', { name: 'Correct payment method', exact: true });
  await dialog.getByRole('combobox').selectOption('other');
  await dialog.getByLabel('Reason', { exact: true }).fill('Original payment was received by QR');
  await dialog.getByRole('checkbox').check();
  await expect(dialog.locator('.adjustment-impact')).toContainText('-6,500');
  await dialog.getByRole('button', { name: 'Confirm method correction', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Payment method correction', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.getByRole('button', { name: 'Record refund', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Record a refund', exact: true });
  await dialog.getByLabel('Refund amount (MMK)', { exact: true }).fill('1000');
  await dialog.getByRole('combobox').selectOption('other');
  await dialog.getByLabel('Reason', { exact: true }).fill('Approved service recovery');
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button', { name: 'Confirm refund record', exact: true }).click();
  const refund = page.getByRole('dialog', { name: 'Refund receipt', exact: true });
  await expect(refund.locator('.receipt-paper-total')).toContainText('1,000');
  await expect(refund).toContainText(order.payment.receipt_number);
  await page.screenshot({ path: 'test-results/' + info.project.name + '-refund-receipt.png', fullPage: true });
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await expect(page.locator('.payment-balance')).toContainText('5,500');
  await page.getByRole('button', { name: 'Receipt', exact: true }).click();
  const original = page.getByRole('dialog', { name: 'Payment complete', exact: true });
  await expect(original.locator('.receipt-paper-total')).toContainText('6,500');
  await expect(original.locator('.receipt-paper')).toContainText('Rice');
  await expect(original.locator('.receipt-paper')).toContainText('Cash');
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.getByRole('button', { name: 'Record refund', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Record a refund', exact: true });
  await dialog.getByLabel('Refund amount (MMK)', { exact: true }).fill('500');
  await dialog.getByRole('combobox').selectOption('cash');
  await dialog.getByLabel('Reason', { exact: true }).fill('Agreed additional cash refund');
  await dialog.getByRole('checkbox').check();
  await dialog.getByRole('button', { name: 'Confirm refund record', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Refund receipt', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.goto('/shifts');
  await expect(page.locator('.shift-metric.highlight')).toContainText('9,500');
  await expect(page.locator('.shift-financial-adjustments article')).toHaveCount(3);
  await page.goto('/sales');
  await expect(page.locator('.refund-summary')).toContainText('1,500');
  await expect(page.locator('.refund-summary')).toContainText('5,000');
  await expect(page.locator('.adjustment-report tbody tr')).toHaveCount(3);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/' + info.project.name + '-refund-sales.png', fullPage: true });
});

test('a full takeaway refund can stop preparation while the original receipt remains printable', async ({ page }, info) => {
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = 'stop-' + info.project.name + '-' + Date.now();
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Owner', email: code + '@example.test', password: 'Refund123!', password_confirmation: 'Refund123!', business_name: 'Refund Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  const post = async (path: string, data: object) => {
    const response = await page.request.post('/api/v1/' + path, { headers: { 'X-CSRF-TOKEN': account.csrf, 'Idempotency-Key': randomUUID() }, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await post('setup', { name: 'Refund Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: true, tables: [], menu: [{ name: 'Rice', category: 'Main', price: 6500 }] });
  const state = await (await page.request.get('/api/v1/state')).json();
  let order = await post('orders', { type: 'takeaway' });
  order = await post(`orders/${order.id}/add-item`, { version: order.version, menu_item_id: state.menu[0].id, quantity: 1 });
  order = await post(`orders/${order.id}/submit`, { version: order.version });
  order = await post(`orders/${order.id}/pay`, { version: order.version, method: 'cash', tendered: 7000 });
  await page.goto(`/orders/${order.id}`);
  await page.getByRole('button', { name: 'Record refund', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Record a refund', exact: true });
  await dialog.getByLabel('Reason', { exact: true }).fill('Takeaway cancelled by customer');
  await dialog.getByRole('checkbox', { name: /Stop preparation/ }).check();
  await dialog.getByRole('checkbox', { name: /I have returned/ }).check();
  await dialog.getByRole('button', { name: 'Confirm refund record', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Refund receipt', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Record refund', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Receipt', exact: true }).click();
  const receipt = page.getByRole('dialog', { name: 'Payment complete', exact: true });
  await expect(receipt.locator('.receipt-paper')).toContainText('Rice');
  await expect(receipt.locator('.receipt-paper-total')).toContainText('6,500');
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.goto('/kitchen');
  await expect(page.locator('.cancel-reason')).toContainText('Refund: Takeaway cancelled by customer');
  await page.getByRole('button', { name: 'Acknowledge', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Acknowledge', exact: true })).toHaveCount(0);
});
