import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('guest menu QR, order requests, staff acceptance and decline work on both screens', async ({ page, browser }, info) => {
  test.setTimeout(75000);
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = `guest-${info.project.name}-${Date.now()}`;
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Owner', email: code + '@example.test', password: 'Secret123!', password_confirmation: 'Secret123!', business_name: 'Guest Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  const post = async (path: string, data: object) => {
    const response = await page.request.post('/api/v1/' + path, { headers: { 'X-CSRF-TOKEN': account.csrf, 'Idempotency-Key': randomUUID() }, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await post('setup', { name: 'Guest Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: false, tables: [{ name: 'A1', seats: 4 }], menu: [{ name: 'Rice', category: 'Main', price: 6500 }] });
  const state = await (await page.request.get('/api/v1/state')).json();
  await page.goto('/guest-orders');
  await page.getByRole('button', { name: 'Menu & QR codes', exact: true }).click();
  await page.getByRole('checkbox', { name: 'Enable public guest menu', exact: true }).check();
  await page.getByRole('checkbox', { name: 'Accept guest order requests', exact: true }).check();
  await page.getByRole('button', { name: 'Save menu settings', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save menu settings', exact: true })).toBeDisabled();
  await page.locator('.guest-link-card').filter({ has: page.getByRole('heading', { name: 'Table A1', exact: true }) }).getByRole('button', { name: 'Create QR link', exact: true }).click();
  const qr = page.getByRole('dialog');
  await expect(qr.getByRole('img', { name: 'Menu QR code for Table A1', exact: true })).toBeVisible();
  const url = (await qr.locator('.qr-url').innerText()).trim();
  await qr.getByRole('img', { name: 'Menu QR code for Table A1', exact: true }).screenshot({ path: `test-results/${info.project.name}-menu-qr.png` });
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  const guest = await browser.newPage({ viewport: info.project.name === 'phone' ? { width: 360, height: 800 } : { width: 1200, height: 900 } });
  await guest.goto(url);
  await expect(guest.getByRole('heading', { name: 'Guest Cafe', exact: true })).toBeVisible();
  await expect(guest).toHaveURL(url);
  const requestRice = async (quantity: string) => {
    await guest.getByRole('button', { name: 'Choose Rice', exact: true }).click();
    let dialog = guest.getByRole('dialog');
    await dialog.getByLabel('Quantity', { exact: true }).fill(quantity);
    await dialog.getByLabel('Preparation notes (optional)', { exact: true }).fill('No onion');
    await dialog.getByRole('button', { name: /Add to order/ }).click();
    await guest.getByRole('button', { name: /View order/ }).click();
    dialog = guest.getByRole('dialog');
    await expect(dialog).toContainText('No onion');
    await dialog.getByRole('button', { name: 'Submit order', exact: true }).click();
    await expect(guest.getByRole('heading', { name: 'Order sent', exact: true })).toBeVisible();
  };
  await requestRice('2');
  await guest.reload();
  await expect(guest.getByRole('heading', { name: 'Order sent', exact: true })).toBeVisible();
  await page.getByRole('button', { name: /Needs review/ }).click();
  await page.getByRole('button', { name: 'Review & accept', exact: true }).click();
  const accept = page.getByRole('dialog');
  await accept.getByRole('checkbox').check();
  await accept.getByRole('button', { name: 'Accept & send to kitchen', exact: true }).click();
  await expect(guest.getByRole('heading', { name: 'Order confirmed', exact: true })).toBeVisible({ timeout: 12000 });
  let updated = await (await page.request.get('/api/v1/state')).json();
  expect(updated.orders[0].items[0].status).toBe('sent');
  expect(updated.orders[0].items[0].quantity).toBe(2);
  await guest.getByRole('button', { name: 'Order more', exact: true }).click();
  await requestRice('1');
  await page.getByRole('button', { name: 'Decline', exact: true }).click();
  const decline = page.getByRole('dialog');
  await decline.getByLabel('Reason shown to guest', { exact: true }).fill('Please speak with staff about your request.');
  await decline.getByRole('button', { name: 'Decline request', exact: true }).click();
  await expect(guest.locator('.guest-status')).toContainText('Please speak with staff about your request.', { timeout: 12000 });
  expect(await guest.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await guest.screenshot({ path: `test-results/${info.project.name}-guest-menu.png`, fullPage: true });
  await page.getByRole('button', { name: 'Reviewed today', exact: true }).click();
  await expect(page.locator('.guest-request')).toHaveCount(2);
  await page.screenshot({ path: `test-results/${info.project.name}-guest-requests.png`, fullPage: true });
  await guest.close();
});


