import { test, expect } from '@playwright/test';

test('manager configures sizes and extras and staff selections reach kitchen and receipt', async ({ page }, info) => {
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = 'options-' + info.project.name + '-' + Date.now();
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Options Owner', email: code + '@example.test', password: 'Options123!', password_confirmation: 'Options123!', business_name: 'Options Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  const setup = await page.request.post('/api/v1/setup', { headers: { 'X-CSRF-TOKEN': account.csrf }, data: { name: 'Options Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: true, tables: [], menu: [{ name: 'Rice', category: 'Main', price: 6500 }] } });
  expect(setup.ok()).toBeTruthy();
  await page.goto('/menu');
  await page.getByRole('button', { name: 'Sizes and add-ons for Rice', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Add size', exact: true }).click();
  await dialog.getByLabel('Size 1 name', { exact: true }).fill('Small');
  await dialog.getByLabel('Size 1 price', { exact: true }).fill('5000');
  await dialog.getByRole('button', { name: 'Add size', exact: true }).click();
  await dialog.getByLabel('Size 2 name', { exact: true }).fill('Large');
  await dialog.getByLabel('Size 2 price', { exact: true }).fill('8000');
  await dialog.getByRole('button', { name: 'Add extra', exact: true }).click();
  await dialog.getByLabel('Add-on 1 name', { exact: true }).fill('Extra egg');
  await dialog.getByLabel('Add-on 1 price', { exact: true }).fill('500');
  await page.screenshot({ path: 'test-results/' + info.project.name + '-options-editor.png', fullPage: true });
  await dialog.getByRole('button', { name: 'Save sizes & add-ons', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.options-count')).toHaveText('2 sizes / 1 add-on');
  await page.goto('/takeaway');
  await page.getByRole('button', { name: 'New takeaway', exact: true }).first().click();
  await page.getByRole('button', { name: 'Start takeaway order', exact: true }).click();
  await expect(page).toHaveURL(/\/orders\/\d+$/);
  const orderURL = page.url();
  await page.getByRole('button', { name: 'Add Rice', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('radio', { name: /Large/ }).check();
  await dialog.getByRole('checkbox', { name: /Extra egg/ }).check();
  await dialog.getByLabel('Quantity', { exact: true }).fill('2');
  await expect(dialog.locator('.option-price-preview')).toContainText('17,000');
  await page.screenshot({ path: 'test-results/' + info.project.name + '-choose-options.png', fullPage: true });
  await dialog.getByRole('button', { name: 'Add to order', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  if (info.project.name === 'phone') await page.getByRole('button', { name: /View order/ }).click();
  await expect(page.locator('.cart-line .item-options')).toContainText('Large');
  await page.getByRole('button', { name: 'Edit choices for Rice', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('radio', { name: /Small/ }).check();
  await dialog.getByRole('checkbox', { name: /Extra egg/ }).uncheck();
  await dialog.getByLabel('Quantity', { exact: true }).fill('1');
  await dialog.getByRole('button', { name: 'Update item choices', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.cart-total')).toContainText('5,000');
  if (info.project.name === 'phone') await page.getByRole('button', { name: 'Close current order', exact: true }).click();
  await page.getByRole('button', { name: 'Add Rice', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('radio', { name: /Large/ }).check();
  await dialog.getByRole('checkbox', { name: /Extra egg/ }).check();
  await dialog.getByRole('button', { name: 'Add to order', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  if (info.project.name === 'phone') await page.getByRole('button', { name: /View order/ }).click();
  await page.getByRole('button', { name: 'Send 2 items to kitchen', exact: true }).click();
  await page.goto('/kitchen');
  await expect(page.locator('.kitchen-ticket .item-options').filter({ hasText: 'Extra egg' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.goto(orderURL);
  if (info.project.name === 'phone') await page.getByRole('button', { name: /View order/ }).click();
  await page.getByRole('button', { name: 'Collect payment', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByLabel('Cash received (MMK)', { exact: true }).fill('15000');
  await dialog.getByRole('button', { name: 'Confirm payment', exact: true }).click();
  const receipt = page.getByRole('dialog', { name: 'Payment complete', exact: true });
  await expect(receipt.locator('.receipt-paper-total')).toContainText('13,500');
  await expect(receipt.locator('.item-options').filter({ hasText: 'Extra egg' })).toBeVisible();
  await page.screenshot({ path: 'test-results/' + info.project.name + '-options-receipt.png', fullPage: true });
});

test('staff can remove an extra that was retired while its item was still a draft', async ({ page }, info) => {
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = 'retired-' + info.project.name + '-' + Date.now();
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Owner', email: code + '@example.test', password: 'Options123!', password_confirmation: 'Options123!', business_name: 'Retired Extra Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  let sequence = 0;
  const post = async (path: string, data: object) => {
    const response = await page.request.post('/api/v1/' + path, { headers: { 'X-CSRF-TOKEN': account.csrf, 'Idempotency-Key': code + '-' + ++sequence }, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await post('setup', { name: 'Retired Extra Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: true, tables: [], menu: [{ name: 'Rice', category: 'Main', price: 6500 }] });
  let state = await (await page.request.get('/api/v1/state')).json();
  const foodId = state.menu[0].id;
  await post('manage/menu-options', { id: foodId, options_version: 1, variants: [], addons: [{ name: 'Extra egg', price: 500, active: true }] });
  state = await (await page.request.get('/api/v1/state')).json();
  let order = await post('orders', { type: 'takeaway' });
  order = await post(`orders/${order.id}/add-item`, { version: order.version, menu_item_id: foodId, quantity: 1, options_version: 2, addon_ids: [state.menu[0].options[0].id] });
  await post('manage/menu-options', { id: foodId, options_version: 2, variants: [], addons: [] });
  await page.goto(`/orders/${order.id}`);
  if (info.project.name === 'phone') await page.getByRole('button', { name: /View order/ }).click();
  await page.getByRole('button', { name: 'Edit choices for Rice', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await expect(dialog.getByRole('button', { name: 'Update item choices', exact: true })).toBeDisabled();
  await dialog.getByRole('checkbox', { name: /Extra egg/ }).uncheck();
  await dialog.getByRole('button', { name: 'Update item choices', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.cart-total')).toContainText('6,500');
  await expect(page.locator('.cart-line .item-options')).toHaveCount(0);
  await page.getByRole('button', { name: 'Send 1 items to kitchen', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Collect payment', exact: true })).toBeEnabled();
});
