import { test, expect, type Page } from '@playwright/test';

async function login(page: Page) {
  await page.goto('/');
  await page.getByLabel('Email', { exact: true }).fill('manager@littlelemon.local');
  await page.getByLabel('Password', { exact: true }).fill('Lemon2026!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your floor, at a glance.' })).toBeVisible();
}
async function openCart(page: Page, phone: boolean) {
  if (phone) await page.getByRole('button', { name: /View order ·/ }).click();
}
async function closeCart(page: Page, phone: boolean) {
  if (phone) await page.getByRole('button', { name: 'Close current order', exact: true }).click();
}
async function noOverflow(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
}

