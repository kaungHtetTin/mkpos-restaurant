test('square crop saves the selected pixels and can be cancelled or adjusted later', async ({ page }, info) => {
  await login(page); await page.goto('/menu');
  await page.getByRole('button', { name: 'Edit Shan noodles', exact: true }).click();
  const base64 = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 600; canvas.height = 300;
    const context = canvas.getContext('2d')!;
    context.fillStyle = '#ff0000'; context.fillRect(0, 0, 200, 300);
    context.fillStyle = '#00ff00'; context.fillRect(200, 0, 200, 300);
    context.fillStyle = '#0000ff'; context.fillRect(400, 0, 200, 300);
    return canvas.toDataURL('image/png').split(',')[1];
  });
  const fixture = { name: 'wide-food.png', mimeType: 'image/png', buffer: Buffer.from(base64, 'base64') };
  await page.getByLabel('Choose food photo', { exact: true }).setInputFiles(fixture);
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Cancel crop', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Food photo preview', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Save changes', exact: true })).toBeEnabled();
  await page.getByLabel('Choose food photo', { exact: true }).setInputFiles(fixture);
  const cropArea = page.getByRole('group', { name: 'Photo crop area', exact: true });
  const zoom = page.getByRole('slider', { name: 'Photo zoom', exact: true });
  await expect(zoom).toBeEnabled();
  await zoom.focus(); await zoom.press('End');
  await expect(zoom).toHaveValue('3');
  await page.getByRole('button', { name: 'Reset', exact: true }).click();
  await expect(zoom).toHaveValue('1');
  const bounds = await cropArea.boundingBox();
  expect(bounds).not.toBeNull();
  expect(Math.abs(bounds!.width - bounds!.height)).toBeLessThan(1);
  await cropArea.scrollIntoViewIfNeeded();
  const currentBounds = (await cropArea.boundingBox())!;
  const before = await page.getByRole('img', { name: 'Photo to crop', exact: true }).evaluate(image => image.style.left);
  await page.mouse.move(currentBounds.x + currentBounds.width / 2, currentBounds.y + currentBounds.height / 2);
  await page.mouse.down();
  await page.mouse.move(currentBounds.x + currentBounds.width / 2 + 30, currentBounds.y + currentBounds.height / 2, { steps: 5 });
  await page.mouse.up();
  const after = await page.getByRole('img', { name: 'Photo to crop', exact: true }).evaluate(image => image.style.left);
  expect(after).not.toBe(before);
  await zoom.focus(); await zoom.press('End');
  await cropArea.focus();
  for (let move = 0; move < 10; move++) await cropArea.press('Shift+ArrowRight');
  await noOverflow(page);
  await page.screenshot({ path: `test-results/${info.project.name}-cropper.png`, fullPage: true });
  await page.getByRole('button', { name: 'Use cropped photo', exact: true }).click();
  const preview = page.getByRole('img', { name: 'Food photo preview', exact: true });
  await expect(preview).toHaveJSProperty('naturalWidth', 100);
  await expect(preview).toHaveJSProperty('naturalHeight', 100);
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  const saved = page.getByRole('img', { name: 'Shan noodles', exact: true });
  await expect(saved).toHaveJSProperty('naturalWidth', 100);
  await expect(saved).toHaveJSProperty('naturalHeight', 100);
  expect(await saved.evaluate(image => {
    const canvas = document.createElement('canvas'); canvas.width = 1; canvas.height = 1;
    const context = canvas.getContext('2d')!; context.drawImage(image, 0, 0, 1, 1);
    return Array.from(context.getImageData(0, 0, 1, 1).data);
  })).toEqual([255, 0, 0, 255]);
  await page.getByRole('button', { name: 'Edit Shan noodles', exact: true }).click();
  await page.getByRole('button', { name: 'Adjust crop', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Use cropped photo', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Cancel crop', exact: true }).click();
  await expect(page.getByRole('img', { name: 'Food photo preview', exact: true })).toHaveJSProperty('naturalWidth', 100);
  await page.getByRole('button', { name: 'Remove photo', exact: true }).click();
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.getByRole('img', { name: 'Shan noodles', exact: true })).toHaveCount(0);
});

