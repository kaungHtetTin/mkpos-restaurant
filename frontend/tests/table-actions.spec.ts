import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';

test('table moves and combined bills preserve occupancy, billing groups and checkout', async ({ page }, info) => {
  test.setTimeout(75000);
  const phone = info.project.name === 'phone';
  const session = await (await page.request.get('/api/v1/session')).json();
  const code = 'tables-' + info.project.name + '-' + Date.now();
  const registration = await page.request.post('/api/v1/register', { headers: { 'X-CSRF-TOKEN': session.csrf }, data: { name: 'Tables Owner', email: code + '@example.test', password: 'Tables123!', password_confirmation: 'Tables123!', business_name: 'Table Test Cafe', business_code: code } });
  expect(registration.status()).toBe(201);
  const account = await registration.json();
  const post = async (path: string, data: object) => {
    const response = await page.request.post('/api/v1/' + path, { headers: { 'X-CSRF-TOKEN': account.csrf, 'Idempotency-Key': randomUUID() }, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await post('setup', { name: 'Table Test Cafe', currency: 'MMK', timezone: 'Asia/Yangon', other_payment_label: 'QR / Card', takeaway_only: false, tables: [{ name: 'Table 01', seats: 4 }, { name: '02', seats: 4 }, { name: '03', seats: 6 }, { name: 'Window with a long table name', seats: 4 }], menu: [{ name: 'Rice', category: 'Main', price: 6500 }] });
  await page.goto('/tables');
  const prefixedCard=page.getByRole('button',{name:'Table 01, available',exact:true});
  await expect(prefixedCard.locator('.table-card-title strong')).toHaveText('Table 01');
  await expect(prefixedCard.locator('.table-drawing-label')).toHaveText('01');
  await expect(page.getByRole('button',{name:'Table 02, available',exact:true}).locator('.table-drawing-label')).toHaveText('02');
  const longLabel=page.getByRole('button',{name:'Table Window with a long table name, available',exact:true}).locator('.table-drawing-label');
  await expect(longLabel).toHaveCSS('white-space','nowrap');
  await page.getByPlaceholder('Find a table...').fill('Table 01');await expect(page.locator('.table-card')).toHaveCount(1);
  await page.getByPlaceholder('Find a table...').fill('');await expect(page.locator('.table-card')).toHaveCount(4);
  await page.locator('.table-grid').screenshot({path:`test-results/${info.project.name}-table-labels.png`});
  await prefixedCard.click();
  await expect(page.getByRole('heading',{name:'Table 01.',exact:true})).toBeVisible();
  await expect(page).toHaveURL(/\/orders\/\d+$/);
  const targetUrl = page.url();
  await page.getByRole('button', { name: 'Add Rice', exact: true }).click();
  if (phone) await page.getByRole('button', { name: /View order/ }).click();
  await page.getByRole('button', { name: 'Send 1 items to kitchen', exact: true }).click();
  if (phone) await page.getByRole('button', { name: 'Close current order', exact: true }).click();
  await page.getByRole('button', { name: 'Move / combine tables', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByRole('radio', { name: /Table 03/ }).check();
  await dialog.getByLabel('Reason', { exact: true }).fill('Guests requested a window table');
  await dialog.getByRole('button', { name: 'Move order', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Table 03.', exact: true })).toBeVisible();
  await page.goto('/tables');
  await expect(page.getByRole('button', { name: 'Table 01, available', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Table 03, occupied', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Table 02, available', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Table 02.', exact: true })).toBeVisible();
  const sourceId = Number(page.url().split('/').at(-1));
  await page.getByRole('button', { name: 'Add Rice', exact: true }).click();
  await expect(page.locator('.cart-total')).toContainText('6,500');
  await page.getByRole('button', { name: 'Move / combine tables', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: 'Combine bills', exact: true }).click();
  await dialog.getByRole('radio', { name: /Table 03/ }).check();
  await dialog.getByLabel('Reason', { exact: true }).fill('Guests are dining together');
  await dialog.getByRole('checkbox').check();
  await expect(dialog.locator('.table-action-total')).toContainText('13,000');
  await page.screenshot({ path: 'test-results/' + info.project.name + '-combine-preview.png', fullPage: true });
  await dialog.getByRole('button', { name: 'Confirm and combine bills', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page).toHaveURL(targetUrl);
  await expect(page.getByRole('heading', { name: 'Table 02 + 03.', exact: true })).toBeVisible();
  await page.goto('/tables');
  await expect(page.getByRole('button', { name: 'Table 02, occupied', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Table 03, occupied', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/' + info.project.name + '-combined-floor.png', fullPage: true });
  await page.getByRole('button', { name: 'Table 02, occupied', exact: true }).click();
  await expect(page).toHaveURL(targetUrl);
  if (phone) await page.getByRole('button', { name: /View order/ }).click();
  await page.getByRole('button', { name: 'Add discount', exact: true }).click();
  dialog = page.getByRole('dialog');
  await dialog.getByRole('combobox', { name: 'Bill portion', exact: true }).selectOption(String(sourceId));
  await dialog.getByRole('combobox', { name: 'Discount type', exact: true }).selectOption('fixed');
  await dialog.getByLabel('Discount amount (MMK)', { exact: true }).fill('500');
  await dialog.getByLabel('Approval reason', { exact: true }).fill('Approved group courtesy');
  await dialog.getByRole('button', { name: 'Approve discount', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.cart-total')).toContainText('12,500');
  await page.getByRole('button', { name: 'Send 1 items to kitchen', exact: true }).click();
  let order = (await (await page.request.get('/api/v1/state')).json()).orders.find((order: { id: number }) => order.id === Number(targetUrl.split('/').at(-1)));
  for (const item of order.items) {
    if (item.status === 'sent') order = await post(`orders/${order.id}/ready`, { version: order.version, item_id: item.id });
    if (['sent', 'ready'].includes(item.status)) order = await post(`orders/${order.id}/serve`, { version: order.version, item_id: item.id });
  }
  await expect(page.getByRole('button', { name: 'Collect payment', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Collect payment', exact: true }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog.locator('.payment-total')).toContainText('12,500');
  await dialog.getByLabel('Cash received (MMK)', { exact: true }).fill('13000');
  await dialog.getByRole('button', { name: 'Confirm payment', exact: true }).click();
  const receipt = page.getByRole('dialog', { name: 'Payment complete', exact: true });
  await expect(receipt.locator('.receipt-paper-total')).toContainText('12,500');
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.goto('/tables');
  await expect(page.getByRole('button', { name: 'Table 02, available', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Table 03, available', exact: true })).toBeVisible();
});
